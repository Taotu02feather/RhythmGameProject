const uint8_t* Renderer::GetCharBitmap(char c) {
    unsigned char uc = static_cast<unsigned char>(c);
    if (uc >= 32 && uc <= 126) return FONT_DATA[uc - 32];
    return FONT_DATA[0];
}

Renderer::Renderer() = default;

Renderer::~Renderer() { Shutdown(); }

bool Renderer::Initialize(SDL_Window* window) {
    if (!window) { std::cerr << "Renderer: null window" << std::endl; return false; }
    m_sdlRenderer = SDL_CreateRenderer(window, -1,
        SDL_RENDERER_ACCELERATED | SDL_RENDERER_PRESENTVSYNC);
    if (!m_sdlRenderer) { std::cerr << "SDL_CreateRenderer: " << SDL_GetError() << std::endl; return false; }
    std::cout << "Renderer OK." << std::endl;
    return true;
}

void Renderer::Shutdown() {
    if (m_font) { TTF_CloseFont(m_font); m_font = nullptr; }
    if (m_sdlRenderer) { SDL_DestroyRenderer(m_sdlRenderer); m_sdlRenderer = nullptr; }
}

void Renderer::BeginFrame() {}
void Renderer::EndFrame() { SDL_RenderPresent(m_sdlRenderer); }

void Renderer::ClearScreen(uint8_t r, uint8_t g, uint8_t b, uint8_t a) {
    SDL_SetRenderDrawColor(m_sdlRenderer, r, g, b, a);
    SDL_RenderClear(m_sdlRenderer);
}

void Renderer::DrawRect(int x, int y, int w, int h, uint8_t r, uint8_t g, uint8_t b, uint8_t a) {
    SDL_SetRenderDrawColor(m_sdlRenderer, r, g, b, a);
    SDL_Rect rect = {x, y, w, h};
    SDL_RenderFillRect(m_sdlRenderer, &rect);
}

// ============ SDL_ttf text ============

bool Renderer::LoadFont(const std::string& path, int size) {
    if (m_font) { TTF_CloseFont(m_font); m_font = nullptr; }
    m_font = TTF_OpenFont(path.c_str(), size);
    if (!m_font) { std::cerr << "TTF_OpenFont(" << path << "): " << TTF_GetError() << std::endl; return false; }
    m_fontSize = size;
    std::cout << "Font loaded: " << path << " " << size << "px" << std::endl;
    return true;
}

void Renderer::DrawTTFText(const std::string& text, int x, int y,
                            uint8_t r, uint8_t g, uint8_t b, uint8_t a) {
    if (!m_font || text.empty()) return;
    SDL_Color fg = {r, g, b, a};
    SDL_Surface* surf = TTF_RenderUTF8_Blended(m_font, text.c_str(), fg);
    if (!surf) return;
    SDL_Texture* tex = SDL_CreateTextureFromSurface(m_sdlRenderer, surf);
    SDL_Rect dst = {x, y, surf->w, surf->h};
    SDL_RenderCopy(m_sdlRenderer, tex, nullptr, &dst);
    SDL_DestroyTexture(tex);
    SDL_FreeSurface(surf);
}

int Renderer::GetTTFTextWidth(const std::string& text) {
    if (!m_font) return 0;
    int w, h;
    TTF_SizeUTF8(m_font, text.c_str(), &w, &h);
    return w;
}

int Renderer::TTFTextHeight() {
    if (!m_font) return 0;
    return TTF_FontHeight(m_font);
}

// ============ 5x7 pixel font ============

void Renderer::DrawPixelChar(char c, int x, int y,
                              uint8_t r, uint8_t g, uint8_t b, uint8_t a, int s) {
    const uint8_t* bm = GetCharBitmap(c);
    SDL_SetRenderDrawColor(m_sdlRenderer, r, g, b, a);
    for (int row = 0; row < 7; ++row)
        for (int col = 0; col < 5; ++col)
            if (bm[row] & (1 << (4 - col))) {
                SDL_Rect px = {x + col * s, y + row * s, s, s};
                SDL_RenderFillRect(m_sdlRenderer, &px);
            }
}

void Renderer::DrawPixelText(const std::string& text, int x, int y,
                              uint8_t r, uint8_t g, uint8_t b, uint8_t a, int s) {
    int cx = x;
    for (char c : text) {
        if (c == '\n') { cx = x; y += 8 * s; continue; }
        DrawPixelChar(c, cx, y, r, g, b, a, s);
        cx += 6 * s;
    }
}

int Renderer::GetPixelTextWidth(const std::string& text, int s) {
    return (int)text.size() * 6 * s;
}

