const uint8_t* Renderer::GetCharBitmap(char c) {
    unsigned char uc = static_cast<unsigned char>(c);
    if (uc >= 32 && uc <= 126) {
        return FONT_DATA[uc - 32];
    }
    // 默认: 返回空格
    return FONT_DATA[0];
}

Renderer::Renderer() = default;

Renderer::~Renderer() {
    Shutdown();
}

bool Renderer::Initialize(SDL_Window* window) {
    if (!window) {
        std::cerr << "Renderer: Invalid window pointer" << std::endl;
        return false;
    }
    m_sdlRenderer = SDL_CreateRenderer(window, -1,
        SDL_RENDERER_ACCELERATED | SDL_RENDERER_PRESENTVSYNC);
    if (!m_sdlRenderer) {
        std::cerr << "SDL_CreateRenderer failed: " << SDL_GetError() << std::endl;
        return false;
    }
    std::cout << "Renderer initialized successfully." << std::endl;
    return true;
}

void Renderer::Shutdown() {
    if (m_sdlRenderer) {
        SDL_DestroyRenderer(m_sdlRenderer);
        m_sdlRenderer = nullptr;
    }
}

void Renderer::BeginFrame() {}

void Renderer::EndFrame() {
    SDL_RenderPresent(m_sdlRenderer);
}

void Renderer::ClearScreen(uint8_t r, uint8_t g, uint8_t b, uint8_t a) {
    SDL_SetRenderDrawColor(m_sdlRenderer, r, g, b, a);
    SDL_RenderClear(m_sdlRenderer);
}

void Renderer::DrawRect(int x, int y, int w, int h,
                        uint8_t r, uint8_t g, uint8_t b, uint8_t a) {
    SDL_SetRenderDrawColor(m_sdlRenderer, r, g, b, a);
    SDL_Rect rect = { x, y, w, h };
    SDL_RenderFillRect(m_sdlRenderer, &rect);
}

void Renderer::DrawPixelChar(char c, int x, int y,
                             uint8_t r, uint8_t g, uint8_t b, uint8_t a, int scale) {
    const uint8_t* bitmap = GetCharBitmap(c);
    SDL_SetRenderDrawColor(m_sdlRenderer, r, g, b, a);
    for (int row = 0; row < 7; ++row) {
        for (int col = 0; col < 5; ++col) {
            if (bitmap[row] & (1 << (4 - col))) {
                SDL_Rect px = { x + col * scale, y + row * scale, scale, scale };
                SDL_RenderFillRect(m_sdlRenderer, &px);
            }
        }
    }
}

void Renderer::DrawPixelText(const std::string& text, int x, int y,
                             uint8_t r, uint8_t g, uint8_t b, uint8_t a, int scale) {
    int cx = x;
    for (char c : text) {
        if (c == '\n') {
            cx = x;
            y += 8 * scale;
            continue;
        }
        DrawPixelChar(c, cx, y, r, g, b, a, scale);
        cx += 6 * scale;  // 5 像素宽 + 1 像素间距
    }
}

int Renderer::GetTextWidth(const std::string& text, int scale) {
    return static_cast<int>(text.size()) * 6 * scale;
}

